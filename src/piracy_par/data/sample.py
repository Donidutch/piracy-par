"""Synthetic weekly count sample (NOT real piracy data).

IMB incident narrations and coordinates are copyrighted by ICC Commercial Crime Services and
are not redistributed here. The bundled ``synthetic_weekly_counts.csv`` is simulated from a
log-linear PARX with annual seasonality, tuned to resemble the scale of weekly reported
incidents in 2023-2025 (mean about 2.4 per week). Regenerate it with::

    python -m piracy_par.data.sample --out src/piracy_par/data/synthetic_weekly_counts.csv
"""

from __future__ import annotations

import argparse
from importlib import resources
from pathlib import Path

import numpy as np
import pandas as pd

from ..models import LogLinearPARX
from .weekly import load_weekly_counts, seasonal_features

__all__ = ["SAMPLE_PARAMS", "make_synthetic_weekly", "load_sample", "SAMPLE_FILE"]

SAMPLE_FILE = "synthetic_weekly_counts.csv"
#: (d, a, b, c_sin, c_cos) of the generating log-linear PARX
SAMPLE_PARAMS = np.array([0.11, 0.45, 0.30, 0.15, -0.10])
_HEADER = (
    "# SYNTHETIC DATA - simulated from a log-linear PARX, not real IMB piracy counts.\n"
    "# Generated by piracy_par.data.sample.make_synthetic_weekly"
)


def make_synthetic_weekly(
    n_weeks: int = 156, *, start: str = "2023-01-02", seed: int = 2025, params=None
) -> pd.DataFrame:
    """Simulate weekly counts with columns ``week_end, count, season_sin, season_cos``."""
    weeks = pd.date_range(start, periods=n_weeks, freq="W-MON")
    X = seasonal_features(weeks)
    theta = SAMPLE_PARAMS if params is None else np.asarray(params, dtype=float)
    y = LogLinearPARX().simulate(n_weeks, params=theta, X=X, seed=seed, burn_in=300)
    out = X.reset_index(drop=True)
    out.insert(0, "count", y)
    out.insert(0, "week_end", weeks.strftime("%Y-%m-%d"))
    return out


def load_sample() -> pd.Series:
    """Bundled synthetic weekly counts as an integer Series indexed by ``week_end``."""
    ref = resources.files("piracy_par.data").joinpath(SAMPLE_FILE)
    with resources.as_file(ref) as path:
        return load_weekly_counts(path)


def write_sample(path, **kwargs) -> Path:
    path = Path(path)
    df = make_synthetic_weekly(**kwargs)
    with path.open("w", encoding="utf-8", newline="") as fh:
        fh.write(_HEADER + "\n")
        df.to_csv(fh, index=False, float_format="%.6f")
    return path


def main(argv=None) -> None:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--out", default=SAMPLE_FILE)
    ap.add_argument("--weeks", type=int, default=156)
    ap.add_argument("--seed", type=int, default=2025)
    args = ap.parse_args(argv)
    p = write_sample(args.out, n_weeks=args.weeks, seed=args.seed)
    print(f"wrote {p}")


if __name__ == "__main__":
    main()
